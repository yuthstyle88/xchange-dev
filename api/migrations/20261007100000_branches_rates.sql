CREATE TABLE currencies (
    code    char(3) PRIMARY KEY,
    name_th text    NOT NULL,
    name_en text,
    symbol  text
);

CREATE TABLE rates (
    id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    branch_id    text          NOT NULL REFERENCES branches (id),
    code         char(3)       NOT NULL REFERENCES currencies (code),
    buy          numeric(14,4) NOT NULL CHECK (buy > 0),
    sell         numeric(14,4) NOT NULL CHECK (sell >= buy),
    partner_name text          NOT NULL DEFAULT '',
    partner_cost numeric(14,4) CHECK (partner_cost > 0),
    reference    jsonb,
    updated_at   timestamptz   NOT NULL,
    updated_by   text          NOT NULL,
    request_id   text          NOT NULL,
    UNIQUE (branch_id, request_id),
    CHECK ((partner_name = '') = (partner_cost IS NULL))
);
CREATE INDEX rates_branch_code_id_idx ON rates (branch_id, code, id DESC);

CREATE TABLE abandoned_requests (
    branch_id  text        NOT NULL REFERENCES branches (id),
    request_id text        NOT NULL,
    at         timestamptz NOT NULL,
    actor      text        NOT NULL,
    PRIMARY KEY (branch_id, request_id)
);

