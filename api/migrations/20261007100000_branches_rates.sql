CREATE TABLE branches (
    id         text        PRIMARY KEY,
    name       text        NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by text        NOT NULL DEFAULT '',
    request_id text        UNIQUE
);
CREATE UNIQUE INDEX branches_name_lower_key ON branches (lower(name));
