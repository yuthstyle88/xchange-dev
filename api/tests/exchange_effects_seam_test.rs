const MUST_FINISH: Duration = Duration::from_secs(30);

static NEXT: AtomicU64 = AtomicU64::new(0);

fn unique(prefix: &str) -> String {
    let nanos = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .expect("after 1970")
        .as_nanos();
    let n = NEXT.fetch_add(1, Ordering::Relaxed);
    format!("{prefix}_{}_{nanos}_{n}", std::process::id())
}

// ---------------------------------------------------------------- a schema of its own

struct Room {
    pool: PgPool,
    schema: String,
    url: String,
}

impl Room {
    async fn start() -> Self {
        let url = std::env::var("TEST_DATABASE_URL").expect(
            "TEST_DATABASE_URL is not set; these tests need a real PostgreSQL and do not skip",
        );
        let options = PgConnectOptions::from_str(&url).expect("a PostgreSQL URL");
        let database = options.get_database().unwrap_or("").to_owned();
        assert!(
            database.ends_with("_test"),
            "'{database}' does not end in `_test`"
        );
        let schema = unique("xs0_effects");
        let admin = PgPoolOptions::new()
            .max_connections(1)
            .acquire_timeout(MUST_FINISH)
            .connect_with(options.clone())
            .await
            .expect("connect to the test database");
        sqlx::query(AssertSqlSafe(format!("CREATE SCHEMA {schema}")))
            .execute(&admin)
            .await
            .expect("create the test schema");
        admin.close().await;
        let pool = PgPoolOptions::new()
            .max_connections(4)
            .acquire_timeout(MUST_FINISH)
            .connect_with(options.options([("search_path", schema.as_str())]))
            .await
            .expect("connect to the test schema");
        sqlx::query("CREATE TABLE marks (who text NOT NULL)")
            .execute(&pool)
            .await
            .expect("the scratch table");
        Room { pool, schema, url }
    }

    /// How many rows `who` has, seen from outside any transaction.
    async fn marks(&self, who: &str) -> i64 {
        sqlx::query_scalar("SELECT count(*) FROM marks WHERE who = $1")
            .bind(who)
            .fetch_one(&self.pool)
            .await
            .expect("count marks")
    }

    async fn all_marks(&self) -> i64 {
        sqlx::query_scalar("SELECT count(*) FROM marks")
            .fetch_one(&self.pool)
            .await
            .expect("count marks")
    }

    async fn finish(self) {
        let Room { pool, schema, url } = self;
        pool.close().await;
        let admin = PgPoolOptions::new()
            .max_connections(1)
            .acquire_timeout(MUST_FINISH)
            .connect_with(PgConnectOptions::from_str(&url).expect("a PostgreSQL URL"))
            .await
            .expect("connect to drop the schema");
        sqlx::query(AssertSqlSafe(format!("DROP SCHEMA {schema} CASCADE")))
            .execute(&admin)
            .await
            .expect("drop the test schema");
        admin.close().await;
    }
}

async fn mark_in(tx: &mut Transaction<'_, Postgres>, who: &str) {
    sqlx::query("INSERT INTO marks (who) VALUES ($1)")
        .bind(who)
        .execute(&mut **tx)
        .await
        .expect("insert a mark");
}

// ---------------------------------------------------------------- a recording effect

type Log = Arc<Mutex<Vec<String>>>;

struct Recording {
    name: &'static str,
    phase: EffectPhase,
    /// Writes a `marks` row named after itself on the caller's transaction.
    writes: bool,
    /// Answers `Err(Validation("<name> refuses"))` after recording.
    refuses: bool,
    log: Log,
}

impl Recording {
    fn act<'a>(
        &'a self,
        tx: &'a mut Transaction<'_, Postgres>,
        what: &'static str,
    ) -> BoxFuture<'a, AppResult<()>> {
        Box::pin(async move {
            self.log
                .lock()
                .expect("log")
                .push(format!("{}:{what}", self.name));
            if self.writes {
                mark_in(tx, self.name).await;
            }
            if self.refuses {
                return Err(AppError::Validation(format!("{} refuses", self.name)));
            }
            Ok(())
        })
    }
}

impl ExchangeEffect for Recording {
    fn name(&self) -> &'static str {
        self.name
    }

    fn phase(&self) -> EffectPhase {
        self.phase
    }

    fn on_completed_in<'a>(
        &'a self,
        tx: &'a mut Transaction<'_, Postgres>,
        _e: &'a ExchangeCompletedFacts,
    ) -> BoxFuture<'a, AppResult<()>> {
        self.act(tx, "completed")
    }

    fn on_reversed_in<'a>(
        &'a self,
        tx: &'a mut Transaction<'_, Postgres>,
        _r: &'a PostedReversal,
    ) -> BoxFuture<'a, AppResult<()>> {
        self.act(tx, "reversed")
    }
}

fn effect(
    log: &Log,
    name: &'static str,
    phase: EffectPhase,
    writes: bool,
    refuses: bool,
) -> Arc<dyn ExchangeEffect> {
    Arc::new(Recording {
        name,
        phase,
        writes,
        refuses,
        log: log.clone(),
    })
}

fn log() -> Log {
    Arc::new(Mutex::new(Vec::new()))
}

fn seen(log: &Log) -> Vec<String> {
    log.lock().expect("log").clone()
}

fn completed() -> ExchangeCompletedFacts {
    let at = Utc
        .with_ymd_and_hms(2026, 10, 12, 3, 0, 0)
        .single()
        .expect("a time");
    ExchangeCompletedFacts {
        organization_id: Uuid::new_v4(),
        branch_id: BranchId::new("XC-B01"),
        transaction_id: Uuid::new_v4(),
        quote_id: Uuid::new_v4(),
        customer_id: Some("C-1".to_owned()),
        mode: Mode::Live,
        completed_at: at,
        business_date: NaiveDate::from_ymd_opt(2026, 10, 12).expect("a date"),
        reversible_until: at + chrono::Duration::days(1),
    }
}

fn reversed() -> PostedReversal {
    PostedReversal {
        organization_id: Uuid::new_v4(),
        reversal_id: Uuid::new_v4(),
        transaction_id: Uuid::new_v4(),
        customer_id: Some("C-1".to_owned()),
        mode: Mode::Live,
        posted_at: Utc
            .with_ymd_and_hms(2026, 10, 12, 4, 0, 0)
            .single()
            .expect("a time"),
        amount_thb: Decimal::new(350_000, 2),
    }
}

/// What a test's caller does: run `phase` on a fresh transaction, as TX-5 / RV-3 do.
#[derive(Clone, Copy)]
enum Call {
    Completed,
    Reversed,
}

async fn run(
    effects: &ExchangeEffects,
    tx: &mut Transaction<'_, Postgres>,
    call: Call,
    phase: EffectPhase,
) -> AppResult<()> {
    match call {
        Call::Completed => effects.run_completed_in(tx, phase, &completed()).await,
        Call::Reversed => effects.run_reversed_in(tx, phase, &reversed()).await,
    }
}

// ---------------------------------------------------------------- §9.3: no registration

#[tokio::test]
async fn with_no_effect_registered_both_calls_answer_ok_and_write_nothing() {
    let room = Room::start().await;
    for effects in [
        ExchangeEffects::new(Vec::new()),
        exchange_effects::collect(Vec::new()),
        exchange_effects::collect([None, None]),
    ] {
        let mut tx = room.pool.begin().await.expect("begin");
        for call in [Call::Completed, Call::Reversed] {
            for phase in [EffectPhase::Redeem, EffectPhase::Outbox] {
                run(&effects, &mut tx, call, phase)
                    .await
                    .expect("nothing registered: Ok(())");
            }
        }
        tx.commit().await.expect("commit");
    }
    assert_eq!(room.all_marks().await, 0, "no effect, no row");
    room.finish().await;
}

// ---------------------------------------------------------------- §9.3: order and phase

#[tokio::test]
async fn effects_of_one_phase_run_once_each_in_registration_order_and_the_other_phase_is_not_run() {
    let room = Room::start().await;
    for (call, what) in [(Call::Completed, "completed"), (Call::Reversed, "reversed")] {
        let log = log();
        let effects = ExchangeEffects::new(vec![
            effect(&log, "first", EffectPhase::Redeem, false, false),
            effect(&log, "outbox_one", EffectPhase::Outbox, false, false),
            effect(&log, "second", EffectPhase::Redeem, false, false),
            effect(&log, "outbox_two", EffectPhase::Outbox, false, false),
        ]);
        let mut tx = room.pool.begin().await.expect("begin");

        run(&effects, &mut tx, call, EffectPhase::Redeem)
            .await
            .expect("no effect refuses");
        assert_eq!(
            seen(&log),
            [format!("first:{what}"), format!("second:{what}")],
            "the Redeem effects, in order, once each; no Outbox effect"
        );

        run(&effects, &mut tx, call, EffectPhase::Outbox)
            .await
            .expect("no effect refuses");
        assert_eq!(
            seen(&log),
            [
                format!("first:{what}"),
                format!("second:{what}"),
                format!("outbox_one:{what}"),
                format!("outbox_two:{what}"),
            ],
            "then the Outbox effects, in order; the Redeem ones do not run again"
        );
        tx.rollback().await.expect("rollback");
    }
    room.finish().await;
}

// ---------------------------------------------------------------- inside the caller's transaction

#[tokio::test]
async fn an_effects_write_is_on_the_callers_transaction_and_commits_with_it() {
    let room = Room::start().await;
    for call in [Call::Completed, Call::Reversed] {
        let who = match call {
            Call::Completed => "writer_completed",
            Call::Reversed => "writer_reversed",
        };
        let log = log();
        let effects =
            ExchangeEffects::new(vec![effect(&log, who, EffectPhase::Outbox, true, false)]);
        let mut tx = room.pool.begin().await.expect("begin");
        mark_in(&mut tx, "caller").await;
        run(&effects, &mut tx, call, EffectPhase::Outbox)
            .await
            .expect("the effect does not refuse");
        assert_eq!(
            room.marks(who).await,
            0,
            "the effect wrote on the caller's transaction, not on its own connection"
        );
        tx.commit().await.expect("commit");
        assert_eq!(room.marks(who).await, 1, "committed with the caller");
    }
    assert_eq!(room.marks("caller").await, 2);
    room.finish().await;
}

// ---------------------------------------------------------------- §9.3: an Err rolls back

#[tokio::test]
async fn an_effects_err_is_the_answer_later_effects_do_not_run_and_the_rollback_leaves_no_row() {
    let room = Room::start().await;
    for (call, what) in [(Call::Completed, "completed"), (Call::Reversed, "reversed")] {
        let log = log();
        let effects = ExchangeEffects::new(vec![
            effect(&log, "writer", EffectPhase::Redeem, true, false),
            effect(&log, "refuser", EffectPhase::Redeem, false, true),
            effect(&log, "later", EffectPhase::Redeem, true, false),
        ]);
        let mut tx = room.pool.begin().await.expect("begin");
        mark_in(&mut tx, "caller").await;

        let answer = run(&effects, &mut tx, call, EffectPhase::Redeem).await;
        match answer {
            Err(AppError::Validation(message)) => {
                assert_eq!(message, "refuser refuses", "the effect's Err, unchanged")
            }
            Err(other) => panic!("expected the refuser's Validation, got {other:?}"),
            Ok(()) => panic!("an effect refused: the call must answer its Err"),
        }
        assert_eq!(
            seen(&log),
            [format!("writer:{what}"), format!("refuser:{what}")],
            "the effect after the refusal does not run"
        );

        // the caller rolls back on the Err, as TX-5 / RV-3 do
        drop(tx);
        assert_eq!(room.all_marks().await, 0, "nothing persists: {what}");
    }
    room.finish().await;
}

// ---------------------------------------------------------------- §9.3: `None` registers nothing

#[tokio::test]
async fn collect_skips_an_effect_that_is_not_configured_and_keeps_the_order() {
    let room = Room::start().await;
    let log = log();
    let effects = exchange_effects::collect([
        None,
        Some(effect(&log, "a_loyalty", EffectPhase::Outbox, false, false)),
        None,
        Some(effect(
            &log,
            "b_marketing",
            EffectPhase::Outbox,
            false,
            false,
        )),
        None,
    ]);
    let mut tx = room.pool.begin().await.expect("begin");
    effects
        .run_completed_in(&mut tx, EffectPhase::Outbox, &completed())
        .await
        .expect("no effect refuses");
    tx.rollback().await.expect("rollback");
    assert_eq!(
        seen(&log),
        ["a_loyalty:completed", "b_marketing:completed"],
        "the configured effects, in the list's order; `None` is no effect and no error"
    );
    room.finish().await;
}

// ---------------------------------------------------------------- the generated list

/// The shape every destination file's `effect` has, as an `EffectFn` (#1375 §7).
fn unconfigured(_state: &AppState) -> Option<Arc<dyn ExchangeEffect>> {
    None
}

fn effect_files() -> Vec<String> {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("src/bootstrap/exchange_effects");
    let mut stems: Vec<String> = std::fs::read_dir(&dir)
        .unwrap_or_else(|e| panic!("read {}: {e}", dir.display()))
        .filter_map(|e| e.ok())
        .map(|e| e.file_name().to_string_lossy().into_owned())
        .filter(|n| n.ends_with(".rs") && n != "mod.rs")
        .collect();
    stems.sort();
    stems
}

#[test]
fn the_list_has_one_entry_per_effect_file() {
    assert_eq!(
        EXCHANGE_EFFECTS.len(),
        effect_files().len(),
        "every bootstrap/exchange_effects/<destination>.rs is in EXCHANGE_EFFECTS, through build.rs"
    );
    let _shape: EffectFn = unconfigured;
}

/// "Adding a destination is one file" (§6.2): the list comes from `build.rs` scanning the directory, as
/// `outbox_handlers` does, not from a list written by hand in `mod.rs`.
#[test]
fn the_list_is_generated_by_build_rs_from_the_directory() {
    let generated = Path::new(env!("OUT_DIR")).join("exchange_effects.rs");
    let code = std::fs::read_to_string(&generated).unwrap_or_else(|e| {
        panic!(
            "build.rs writes {} from src/bootstrap/exchange_effects/: {e}",
            generated.display()
        )
    });
    assert!(
        code.contains("EXCHANGE_EFFECTS"),
        "the generated file declares EXCHANGE_EFFECTS:\n{code}"
    );
    for file in effect_files() {
        let module = file.trim_end_matches(".rs");
        assert!(
            code.contains(&format!("{module}::effect")),
            "the generated list names {module}::effect:\n{code}"
        );
    }

    let mod_rs =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("src/bootstrap/exchange_effects/mod.rs");
    let source = std::fs::read_to_string(&mod_rs).expect("read exchange_effects/mod.rs");
    assert!(
        source.contains("include!(") && source.contains("\"/exchange_effects.rs\""),
        "exchange_effects/mod.rs includes the build output"
    );
    assert!(
        !source.contains("pub const EXCHANGE_EFFECTS"),
        "EXCHANGE_EFFECTS is generated, not written by hand in mod.rs"
    );
}
