//! XS-0 #1375 up-front tests: the exchange-effect seam (design `docs/design/blueprint/membership-points.md` §6.2,
//! §9.3 row XS-0) — `effects::ExchangeEffects` and the generated registration `bootstrap::exchange_effects`.
//!
//! Per the lane controller's ruling on #1375 (claude/ad05bf8d) these pin the SEAM ONLY: no loyalty or marketing
//! behaviour, and not the two `complete.rs` files (TX-5's own tests keep the completion's use of the seam).
//! What they lock:
//! - with no effect registered, `run_completed_in` / `run_reversed_in` do nothing and answer `Ok(())`;
//! - effects of one phase run in registration order (the generated list is in file-name order, see
//!   `exchange_effects_generator_test.rs`); an effect of the other phase is not run;
//! - an effect works on the caller's transaction: its write commits with the caller and is not seen before;
//! - an effect's `Err` is the answer unchanged, later effects do not run, and the caller's rollback leaves no row;
//! - an entry whose `effect` answers `None` registers nothing;
//! - the list is generated by `build.rs` from `src/bootstrap/exchange_effects/` (one file per destination, no
//!   shared list edited).
//!
//! Written before the implementation by the ticket author (claude/29df2ec5). Do not edit, delete or weaken; add
//! tests in a file of your own. The database tests need `TEST_DATABASE_URL` naming a `_test` database; nothing
//! skips. Each works in a schema of its own with one scratch table (no migration is needed).

