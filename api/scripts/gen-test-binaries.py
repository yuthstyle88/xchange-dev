#!/usr/bin/env python3
"""One integration-test binary per package.

Cargo builds every top-level `tests/*.rs` file as its own binary, and each one links the
whole package and its dependencies again. With 483 such files the api's CI spent most of
its time in the linker (2026-10-12: median api run 25 min, the linker OOM-killed on Dell).

For every package that has integration tests, this script keeps four things true:
- `tests/all.rs` (or `tests/all_<k>.rs` in `api`) is a fixed stub that `include!`s the module
  list emitted into `OUT_DIR` by `xc-testlist` at build time (add a test file → nothing to
  regenerate);
- Cargo.toml has `autotests = false` and that one `[[test]]` entry;
- a helper module (`tests/<name>/mod.rs`) reaches its siblings through `super::`, not
  `crate::` (the crate root is now all.rs), and its macros are not `#[macro_export]`;
- a test file that declares a helper with macros puts `#[macro_use]` on that `mod`.
Files it rewrites are passed through rustfmt.

Run it after adding a test helper or a package with integration tests (add a test file → nothing to regenerate):

    python3 api/scripts/gen-test-binaries.py          # rewrite every tests/all.rs stub / helper
    python3 api/scripts/gen-test-binaries.py --check  # exit 1 if any is out of date
"""
import pathlib
import re
import subprocess
import sys

N = 4
API = pathlib.Path(__file__).resolve().parent.parent
HEADER = """\
// @generated by api/scripts/gen-test-binaries.py — do not edit by hand.
// Every integration-test file of this package, compiled into one test binary.
// Adding a test file needs no edit here: xc-testlist (build.rs) writes the module list into OUT_DIR.
#![allow(dead_code, clippy::duplicate_mod)]
"""


def is_runner(name):
    return name == "all.rs" or bool(re.fullmatch(r"all_\d+\.rs", name))


def packages():
    for root in [API, *sorted((API / "crates").iterdir())]:
        tests = root / "tests"
        if (root / "Cargo.toml").exists() and tests.is_dir() and any(
            not is_runner(p.name) for p in tests.glob("*.rs")
        ):
            yield root


def render_stub(name):
    return f'{HEADER}\ninclude!(concat!(env!("OUT_DIR"), "/test_list_{name}.rs"));\n'


CARGO_NOTE = "# One test binary per package: tests/all.rs (api/scripts/gen-test-binaries.py).\n"
CARGO_TEST = '\n[[test]]\nname = "all"\npath = "tests/all.rs"\n'


def cargo_toml(root, text):
    """autotests = false (else every file is still a binary of its own) and the [[test]] entries."""
    if "autotests = false" not in text:
        text = text.replace("[package]\n", "[package]\n" + CARGO_NOTE + "autotests = false\n", 1)
    if root == API:
        text = re.sub(
            r'(\n\[\[test\]\]\nname = "all(?:_\d+)?"\npath = "tests/all(?:_\d+)?\.rs"\n)+$',
            "",
            text,
        )
        entries = "".join(
            f'\n[[test]]\nname = "all_{k}"\npath = "tests/all_{k}.rs"\n' for k in range(1, N + 1)
        )
        return text.rstrip("\n") + "\n" + entries
    if 'path = "tests/all.rs"' not in text:
        text = text.rstrip("\n") + "\n" + CARGO_TEST
    return text


def helper(text):
    """A helper module (tests/<name>/mod.rs) is now a child of each test module, not of the crate
    root: siblings are reached through super::, and a test macro cannot be #[macro_export]ed
    (one binary would export the same name once per test file that declares the helper)."""
    text = re.sub(r"\$crate::([a-z_][a-z0-9_]*)::", r"\1::", text)
    text = re.sub(r"(?<![\$\w])crate::", "super::", text)
    return text.replace("#[macro_export]\n", "#[allow(unused_macros)]\n")


def macro_helpers(root):
    return sorted(
        p.parent.name
        for p in (root / "tests").glob("*/mod.rs")
        if re.search(r"(?m)^\s*macro_rules!", p.read_text())
    )


def test_file(text, macro_mods):
    """A test file that declares a helper defining macros needs #[macro_use] on that mod."""
    text = text.replace("crate::snapshot_common::", "snapshot_common::")
    for name in macro_mods:
        text = re.sub(rf"(?m)^(?<!#\[macro_use\]\n)(mod {name};)", r"#[macro_use]\n\1", text)
    return text


def wanted(root):
    """Every file this script owns in one package, with the text it must have."""
    tests = root / "tests"
    files = {root / "Cargo.toml": cargo_toml(root, (root / "Cargo.toml").read_text())}
    for p in tests.glob("*/mod.rs"):
        files[p] = helper(p.read_text())
    mods = macro_helpers(root)
    test_names = sorted(p.name for p in tests.glob("*.rs") if not is_runner(p.name))
    for name in test_names:
        p = tests / name
        files[p] = test_file(p.read_text(), mods)
    if root == API:
        for k in range(1, N + 1):
            files[tests / f"all_{k}.rs"] = render_stub(f"all_{k}")
    else:
        files[tests / "all.rs"] = render_stub("all")
    return files


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for root in packages():
        expected = wanted(root)
        for p in sorted((root / "tests").glob("*.rs")):
            if is_runner(p.name) and p not in expected:
                stale.append(str(p.relative_to(API.parent)))
                if not check:
                    p.unlink()
        for out, text in expected.items():
            if not out.exists() or out.read_text() != text:
                stale.append(str(out.relative_to(API.parent)))
                if not check:
                    out.write_text(text)
                    if out.suffix == ".rs":
                        subprocess.run(["rustfmt", "--edition", "2024", str(out)], check=False)
    if check and stale:
        print("out of date (run python3 api/scripts/gen-test-binaries.py):", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
