export function liveCsvRow(
  branchId: string,
  branchName: string,
  r: TransactionRow,
): string[] {
  return [
    branchId,
    branchName,
    'LIVE',
    r.id,
    r.date,
    r.type,
    r.currency,
    r.amount,
    r.rate,
    r.unitSize,
    r.principal,
    r.fee,
    r.bankFee,
    r.settlement,
    r.method,
    r.status,
    r.shiftId ?? '',
    r.referenceRate ?? '',
    r.referenceValue ?? '',
    r.referenceSpread ?? '',
    r.referencePercent ?? '',
  ];
}
